# 8. Cross-Runtime Parity Verification Status
# ==============================================================================
def test_008_android_cross_runtime_status(parity_data):
    """
    Evaluates cross-runtime status between Python and Android.
    If Android test output file exists, validates cosine agreement >= 0.999.
    Otherwise, marks actual Android on-device inference as UNVERIFIED per user requirements.
    """
    android_export_file = Path(__file__).resolve().parent / "android_embeddings.json"

    if android_export_file.exists():
        with open(android_export_file, "r", encoding="utf-8") as f:
            android_data = json.load(f)

        tolerances = parity_data["metadata"]["tolerances"]
        min_cosine = tolerances["cosine_min"]
        max_abs_diff = tolerances["max_absolute_difference"]

        for item in parity_data["fixtures"]:
            item_id = item["id"]
            if item_id in android_data:
                android_vec = android_data[item_id]
                ref_vec = item["query"]["embedding"]
                sim = cosine_similarity(android_vec, ref_vec)
                abs_diff = max(abs(a - b) for a, b in zip(android_vec, ref_vec))

                assert sim >= min_cosine, f"Android cosine divergence on {item_id}: {sim} < {min_cosine}"
                assert abs_diff <= max_abs_diff, f"Android absolute diff exceeded on {item_id}: {abs_diff}"
    else:
        # Per Mandatory Correction 1:
        # "If no device/emulator is available, run the backend parity checks,
        # implement the Android instrumentation tests, and mark actual Android inference parity as UNVERIFIED."
        pytest.skip(
            "No Android device/emulator connected and android_embeddings.json not found. "
            "Backend parity checks passed; actual Android on-device inference marked UNVERIFIED."
        )
