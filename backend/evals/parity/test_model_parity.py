# 6. Multilingual Parity: English and Hindi
# ==============================================================================
def test_006_multilingual_parity_english_and_hindi(parity_data):
    """
    Validates that the multilingual-e5-small ONNX model produces high-quality
    embeddings for both English and Hindi NCERT Class 10 Science topics.
    """
    hindi_items = [item for item in parity_data["fixtures"] if item["language"] == "hi"]
    english_items = [item for item in parity_data["fixtures"] if item["language"] == "en" and not item["is_out_of_syllabus"]]

    assert len(hindi_items) >= 2, "Insufficient Hindi parity fixtures"
    assert len(english_items) >= 5, "Insufficient English parity fixtures"

    for h_item in hindi_items:
        sim = h_item["direct_cosine_similarity"]
        # Hindi queries must closely match their corresponding Hindi passage
        assert sim >= 0.80, f"Hindi match similarity below 0.80 for {h_item['id']}: {sim}"


