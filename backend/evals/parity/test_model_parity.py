# 5. Shared Test Index Retrieval Ranking
# ==============================================================================
def test_005_retrieval_ranking_on_fixed_index(parity_data):
    """
    Constructs a shared test index from all 10 fixture passages.
    Verifies that for each in-syllabus query, its ground-truth passage ranks #1 (100% Top-1).
    """
    index_passages = [
        {"id": item["id"], "embedding": item["passage"]["embedding"], "chapter": item["chapter"]}
        for item in parity_data["fixtures"]
    ]

    for item in parity_data["fixtures"]:
        if item["is_out_of_syllabus"]:
            continue

        q_vec = item["query"]["embedding"]
        scored = []
        for p in index_passages:
            sim = cosine_similarity(q_vec, p["embedding"])
            scored.append((p["id"], sim))
        scored.sort(key=lambda x: x[1], reverse=True)

        # Ground truth check: #1 ranked passage must be this item's passage
        top_1_id, top_1_sim = scored[0]
        assert top_1_id == item["id"], (
            f"Retrieval ranking mismatch for {item['id']}: "
            f"Expected {item['id']} at rank 1, but got {top_1_id} with sim={top_1_sim:.4f}. "
            f"Item's rank was {[x[0] for x in scored].index(item['id']) + 1}"
        )
        assert top_1_sim >= 0.80, f"Top match similarity too low for {item['id']}: {top_1_sim}"


