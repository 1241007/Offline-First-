# 2. Tokenization, Special Tokens and Attention Masks
# ==============================================================================
def test_002_preprocessing_and_special_tokens(parity_data):
    """Validates token IDs, special tokens (<s>, </s>), and attention masks."""
    import tokenizers

    tok = tokenizers.Tokenizer.from_file(str(local_e5_service.tokenizer_file))

    for item in parity_data["fixtures"]:
        q_ref = item["query"]
        p_ref = item["passage"]

        # 1. Query tokenization check
        enc_q = tok.encode(q_ref["prefixed_text"])
        assert enc_q.ids[:512] == q_ref["token_ids"], f"Token mismatch on {item['id']} query"
        assert enc_q.attention_mask[:512] == q_ref["attention_mask"]

        # Check special tokens (multilingual-e5-small uses XLM-RoBERTa vocabulary)
        # Token 0 is '<s>', Token 2 is '</s>'
        assert enc_q.ids[0] == 0, f"Missing start token <s> on {item['id']}"
        assert enc_q.ids[-1] == 2, f"Missing end token </s> on {item['id']}"

        # 2. Passage tokenization check
        enc_p = tok.encode(p_ref["prefixed_text"])
        assert enc_p.ids[:512] == p_ref["token_ids"], f"Token mismatch on {item['id']} passage"
        assert enc_p.attention_mask[:512] == p_ref["attention_mask"]
        assert enc_p.ids[0] == 0
        assert enc_p.ids[-1] == 2


