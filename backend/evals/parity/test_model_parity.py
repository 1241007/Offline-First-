# 7. Asymmetric Prefix Separation
# ==============================================================================
def test_007_asymmetric_prefix_separation():
    """
    Verifies that 'query: X' and 'passage: X' produce distinct representations,
    guaranteeing that the asymmetric prefix is effective.
    """
    text = "Ohm's law states that potential difference V is proportional to current I."
    q_vec = local_e5_service._run_inference(f"query: {text}")
    p_vec = local_e5_service._run_inference(f"passage: {text}")

    sim = cosine_similarity(q_vec, p_vec)
    # They should be semantically close but mathematically distinct
    assert sim < 0.98, f"Asymmetric prefixes did not separate representations: sim={sim}"
    assert sim > 0.70, f"Asymmetric representations diverged too far: sim={sim}"


