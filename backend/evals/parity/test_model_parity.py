def cosine_similarity(v1, v2):
    """Computes cosine similarity between two float vectors."""
    assert len(v1) == len(v2) == EMBEDDING_DIM
    dot = sum(a * b for a, b in zip(v1, v2))
    norm1 = math.sqrt(sum(a * a for a in v1))
    norm2 = math.sqrt(sum(b * b for b in v2))
    if norm1 < 1e-12 or norm2 < 1e-12:
        return 0.0
    return dot / (norm1 * norm2)


# ==============================================================================
# 1. Pinned Artifact Integrity and Metadata
# ==============================================================================
def test_001_artifact_hashes_and_metadata(parity_data):
    """Confirms exact SHA-256 digests and metadata match pinned specifications."""
    meta = parity_data["metadata"]

    assert meta["model_id"] == DEFAULT_MODEL_NAME
    assert meta["model_version"] == MODEL_VERSION
    assert meta["embedding_dimension"] == 384
    assert meta["max_sequence_length"] == 512
    assert meta["normalization"] == "L2"
    assert meta["pooling"] == "mean_over_attention_mask"

    # Verify model_quantized.onnx SHA-256
    model_path = local_e5_service.model_file
    assert model_path.exists(), f"Model file missing: {model_path}"
    with open(model_path, "rb") as f:
        actual_model_hash = hashlib.sha256(f.read()).hexdigest().lower()
    assert actual_model_hash == ONNX_QUANTIZED_SHA256.lower()
    assert actual_model_hash == meta["model_sha256"].lower()

    # Verify tokenizer.json SHA-256
    tok_path = local_e5_service.tokenizer_file
    assert tok_path.exists(), f"Tokenizer file missing: {tok_path}"
    with open(tok_path, "rb") as f:
        actual_tok_hash = hashlib.sha256(f.read()).hexdigest().lower()
    assert actual_tok_hash == TOKENIZER_SHA256.lower()
    assert actual_tok_hash == meta["tokenizer_sha256"].lower()


