# 3. Pooling and L2 Normalization
# ==============================================================================
def test_003_pooling_and_l2_normalization(parity_data):
    """Validates that all reference vectors have dimension 384 and unit L2 norm."""
    for item in parity_data["fixtures"]:
        for key in ["query", "passage"]:
            vec = item[key]["embedding"]
            assert len(vec) == 384, f"Dimension mismatch in {item['id']} {key}"
            norm = math.sqrt(sum(x * x for x in vec))
            assert abs(norm - 1.0) < 1e-4, f"L2 norm not unit in {item['id']} {key}: {norm}"
            assert all(math.isfinite(x) for x in vec), f"Non-finite value in {item['id']} {key}"


# ==============================================================================
# 4. Live Python ONNX Inference vs Reference Vectors
# ==============================================================================
def test_004_live_python_onnx_inference_agreement(parity_data):
    """
    Reruns live ONNX inference across all fixture queries and passages.
    Measures vector cosine agreement (>= 0.9999) and max absolute difference (< 1e-4).
    """
    assert local_e5_service.is_quantized_model_loaded or local_e5_service.ensure_quantized_model_cached()

    for item in parity_data["fixtures"]:
        # Query check
        live_q_vec = local_e5_service._run_inference(item["query"]["prefixed_text"])
        ref_q_vec = item["query"]["embedding"]
        cos_q = cosine_similarity(live_q_vec, ref_q_vec)
        max_diff_q = max(abs(a - b) for a, b in zip(live_q_vec, ref_q_vec))
        assert cos_q >= 0.9999, f"Query cosine agreement below tolerance on {item['id']}: {cos_q}"
        assert max_diff_q < 1e-4, f"Query absolute diff exceeded on {item['id']}: {max_diff_q}"

        # Passage check
        live_p_vec = local_e5_service._run_inference(item["passage"]["prefixed_text"])
        ref_p_vec = item["passage"]["embedding"]
        cos_p = cosine_similarity(live_p_vec, ref_p_vec)
        max_diff_p = max(abs(a - b) for a, b in zip(live_p_vec, ref_p_vec))
        assert cos_p >= 0.9999, f"Passage cosine agreement below tolerance on {item['id']}: {cos_p}"
        assert max_diff_p < 1e-4, f"Passage absolute diff exceeded on {item['id']}: {max_diff_p}"


