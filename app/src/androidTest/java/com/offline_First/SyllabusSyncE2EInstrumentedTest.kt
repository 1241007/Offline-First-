class TestTokenStorage(private var token: String? = null) : TokenStorage {
    private var userIdentity: com.offline_First.data.local.CachedUserIdentity? = null

    override fun saveTokens(accessToken: String, refreshToken: String) {
        token = accessToken
    }
    override fun getAccessToken(): String? = token
    override fun getRefreshToken(): String? = "mock-refresh-token"
    override fun clearTokens() {
        token = null
    }
    override fun hasTokens(): Boolean = token != null

    override fun saveUserIdentity(userId: String, email: String, fullName: String) {
        userIdentity = com.offline_First.data.local.CachedUserIdentity(userId, email, fullName)
    }

    override fun getUserIdentity(): com.offline_First.data.local.CachedUserIdentity? = userIdentity

    override fun clearUserIdentity() {
        userIdentity = null
    }
}

/**
 * Real Android End-to-End Instrumented Test for Syllabus Sync,
 * executing directly on the Android OS runtime and SQLite database.
 */
@RunWith(AndroidJUnit4::class)
class SyllabusSyncE2EInstrumentedTest {

    private lateinit var appContext: Context
    private lateinit var database: SyllabusDatabase
    private lateinit var syncRepository: SyllabusSyncRepository
    private val backendBaseUrl = "http://127.0.0.1:8000"

    // Valid test JWT token generated by backend JWT_SECRET_KEY
    private val testJwtToken = "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOiJhbmRyb2lkLWUyZS10ZXN0ZXIiLCJlbWFpbCI6InRlc3RlckBlZHVub3ZhLmFpIiwicm9sZSI6InVzZXIiLCJ0eXBlIjoiYWNjZXNzIiwiaWF0IjoxNzkyMDc5MTIwLCJleHAiOjE3OTIwODA5MjB9.rvDj8VdkZYiNiJ8aK-f3FoaYOLGSHD7RVWpJTy3woqg"

    @Before
    fun setUp() {
        appContext = InstrumentationRegistry.getInstrumentation().targetContext
        database = SyllabusDatabase(appContext)

        // Clean any existing test records for Class 10 Math
        val db = database.writableDatabase
        db.delete("syllabus_chunks", "subject = ?", arrayOf("Mathematics"))
        db.delete("syllabus_packs", "pack_id = ?", arrayOf("cbse-10-mathematics"))

        val tokenStorage = TestTokenStorage(testJwtToken)
        val sessionManager = SessionManager(tokenStorage)
        val publicClientFactory = {
            OkHttpClient.Builder()
                .connectTimeout(15, TimeUnit.SECONDS)
                .readTimeout(15, TimeUnit.SECONDS)
                .build()
        }

        val authClient = AuthenticatedApiClient(
            tokenStorage = tokenStorage,
            sessionManager = sessionManager,
            publicClient = publicClientFactory,
            baseUrl = backendBaseUrl
        )

        val syncClient = RemoteSyllabusSyncClient(
            authenticatedClient = authClient,
            baseUrl = backendBaseUrl
        )

        syncRepository = SyllabusSyncRepository(
            syncClient = syncClient,
            database = database
        )
    }

    @After
    fun tearDown() {
        database.close()
    }

    @Test
    fun testFullOnlineSyncAndLocalPersistence() = runBlocking {
        // -------------------------------------------------------------
        // Step 1: Pre-sync state check
        // -------------------------------------------------------------
        assertFalse(
            "Local database should not have math pack before sync",
            database.hasPack("CBSE", "10", "Mathematics")
        )

        // -------------------------------------------------------------
        // Step 2: Trigger real online synchronization
        // -------------------------------------------------------------
        val syncResult = syncRepository.syncCurriculumPack("CBSE", "10", "Mathematics")
        assertTrue("Sync must succeed against backend API: ${syncResult.exceptionOrNull()?.message}", syncResult.isSuccess)
        val downloadedCount = syncResult.getOrNull() ?: 0
        assertEquals("Must download exactly 10 chunks for cbse-10-mathematics", 10, downloadedCount)
        assertTrue("Sync state must be Success", syncRepository.syncState.value is SyllabusSyncState.Success)

        // -------------------------------------------------------------
        // Step 3: Verify local SQLite persistence and schema
        // -------------------------------------------------------------
        assertTrue("Database must report pack presence after sync", database.hasPack("CBSE", "10", "Mathematics"))

        val rDb = database.readableDatabase

        // 3a. Verify syllabus_packs table
        val packCursor = rDb.rawQuery("SELECT pack_id, board, class_grade, subject, academic_year, content_hash, chunk_count FROM syllabus_packs WHERE pack_id = ?", arrayOf("cbse-10-mathematics"))
        packCursor.use { c ->
            assertTrue("Pack record must exist in syllabus_packs", c.moveToFirst())
            assertEquals("cbse-10-mathematics", c.getString(0))
            assertEquals("CBSE", c.getString(1))
            assertEquals("10", c.getString(2))
            assertEquals("Mathematics", c.getString(3))
            assertEquals("2026-27", c.getString(4))
            val hash = c.getString(5)
            assertNotNull("Content hash must not be null", hash)
            assertEquals("Content hash must be 64-char SHA-256", 64, hash.length)
            assertEquals("Stored chunk_count must equal 10", 10, c.getInt(6))
        }

        // 3b. Verify syllabus_chunks table
        val chunkCursor = rDb.rawQuery("SELECT chunk_id, chapter_title, content, embedding FROM syllabus_chunks WHERE subject = 'Mathematics'", null)
        chunkCursor.use { c ->
            assertEquals("Total chunks in SQLite must be 10", 10, c.count)
            while (c.moveToNext()) {
                val chunkId = c.getString(0)
                val chapter = c.getString(1)
                val content = c.getString(2)
                val blob = c.getBlob(3)

                assertNotNull("Chunk ID must be present", chunkId)
                assertNotNull("Chapter must be present", chapter)
                assertTrue("Content must not be empty", content.isNotBlank())
                assertNotNull("Vector embedding BLOB must be present", blob)
                assertEquals("Embedding BLOB must be exactly 1536 bytes (384 * 4)", 1536, blob.size)

                val floats = SyllabusDatabase.blobToFloatArray(blob)
                assertNotNull(floats)
                assertEquals("Vector must unpack to 384 dimensions", 384, floats!!.size)
                for (v in floats) {
                    assertFalse("Embedding value must be finite", v.isNaN() || v.isInfinite())
                }
            }
        }

        // -------------------------------------------------------------
        // Step 4: Idempotent resynchronization
        // -------------------------------------------------------------
        val resyncResult = syncRepository.syncCurriculumPack("CBSE", "10", "Mathematics")
        assertTrue("Resync must succeed", resyncResult.isSuccess)

        // Verify no duplicate rows created
        val countCursor = rDb.rawQuery("SELECT COUNT(*) FROM syllabus_chunks WHERE subject = 'Mathematics'", null)
        val finalCount = countCursor.use { if (it.moveToFirst()) it.getInt(0) else 0 }
        assertEquals("Resync must not create duplicate chunk rows", 10, finalCount)

        // -------------------------------------------------------------
        // Step 5: Offline retrieval simulation (Airplane Mode)
        // -------------------------------------------------------------
        // Query answerable from Class 10 Math curriculum
        val searchResults = database.searchChunks(
            query = "Quadratic Equations roots",
            board = "CBSE",
            classGrade = "10",
            subject = "Mathematics",
            limit = 3
        )
        assertFalse("Offline keyword search must find relevant curriculum chunks", searchResults.isEmpty())
        val topResult = searchResults[0]
        assertTrue("Top chunk match score must be positive", (topResult.relevanceScore ?: 0f) > 0f)
        assertTrue(
            "Retrieved content must relate to algebra or equations",
            topResult.content.contains("Equations", ignoreCase = true) ||
            topResult.content.contains("ALGEBRA", ignoreCase = true) ||
            topResult.content.contains("Linear", ignoreCase = true)
        )

        // -------------------------------------------------------------
        // Step 6: Unsupported / out-of-curriculum query rejection
        // -------------------------------------------------------------
        val unsupportedResults = database.searchChunks(
            query = "quantum entanglement string theory",
            board = "CBSE",
            classGrade = "10",
            subject = "Mathematics",
            limit = 3
        )
        assertTrue("Unsupported out-of-curriculum query must return 0 results", unsupportedResults.isEmpty())
    }
}
